/// The width of `text` in grid units, advances included.
pub fn text_units(text: &str) -> f64 {
    text.chars().map(|c| glyph(c).advance).sum()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_letter_digit_and_mark_has_strokes() {
        for c in ('a'..='z').chain('A'..='Z').chain('0'..='9').chain(".,-:;!?()/%\"'".chars()) {
            let g = glyph(c);
            assert!(!g.strokes.is_empty(), "{c}");
            assert!(g.advance > 0.0);
            for stroke in &g.strokes {
                assert!(stroke.iter().all(|(x, y)| (-0.5..=5.5).contains(x) && (-2.5..=7.5).contains(y)), "{c}: {stroke:?}");
            }
        }
        assert!(glyph(' ').strokes.is_empty());
        // An unknown character draws a box, not nothing and not a panic.
        assert_eq!(glyph('é').strokes.len(), 1);
    }

    #[test]
    fn capitals_are_six_units_high_and_lowercase_four() {
        let top = |c: char| glyph(c).strokes.iter().flatten().map(|p| p.1).fold(f64::NEG_INFINITY, f64::max);
        assert_eq!(top('H'), 6.0);
        assert_eq!(top('x'), 4.0);
        assert_eq!(top('d'), 7.0);
        let bottom = |c: char| glyph(c).strokes.iter().flatten().map(|p| p.1).fold(f64::INFINITY, f64::min);
        assert_eq!(bottom('p'), -2.0);
        assert!(text_units("abc") > text_units("ab"));
    }
}
