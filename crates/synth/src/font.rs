//! A single-stroke alphabet written for the generator: letters, digits and a little punctuation as
//! polylines in a grid four units wide and six high for capitals (x-height 4, ascenders 7,
//! descenders −2). The shapes are original; no font file is used or copied.

/// One glyph: its advance in grid units and its strokes, each a polyline of (x, y) points, y up.
pub struct Glyph {
    pub advance: f64,
    pub strokes: Vec<Vec<(f64, f64)>>,
}

/// The grid units that make one em: the capital height (6 units) is 0.72 em.
pub const UNITS_PER_EM: f64 = 6.0 / 0.72;

fn parse(width: f64, spec: &str) -> Glyph {
    let strokes = spec
        .split(';')
        .map(|stroke| {
            stroke
                .split_whitespace()
                .filter_map(|pair| {
                    let (x, y) = pair.split_once(',')?;
                    Some((x.parse().ok()?, y.parse().ok()?))
                })
                .collect::<Vec<_>>()
        })
        .filter(|s: &Vec<(f64, f64)>| !s.is_empty())
        .collect();
    Glyph { advance: width + 1.4, strokes }
}

